"""Who may see what.

Every read of an asset or a folder goes through the repository, and every read takes a viewer:

    viewer = await access.load_viewer(user_id)          # None if disabled or gone
    page = await access.visible_assets(viewer, limit=50)
    asset = await access.open_asset(viewer, asset_id)   # None if they may not have it

Nothing here is cached. The viewer is rebuilt from the database on each request and holds no
grants, so a share revoked now is denied on the next request rather than at the next login.

The default is that a guest sees nothing. A share opens something up, a restrict closes it and
cannot be reopened by a share made elsewhere, and no grant at all means private, which keeps
them out without promising that a deliberate share somewhere else will not reach in. The vault
is separate from all of that: it conceals from everyone, including an admin, until it is
unlocked.
"""

