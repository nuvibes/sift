"""The catalog's write paths and reads: sites, usernames, people, and what is filed on a file.

The tables live in the kernel because the permission resolver joins them, and their one write path
lives beside them so no feature grows its own copy of an upsert. Each write is keyed on what
already makes a row unique, so a repeat returns the same ids and changes nothing. Nothing here is
permission-scoped: these are system writes and reads made for no viewer (a download runs for
nobody in particular), so they take a database handle rather than going through the repository.

This module is the door: every name a caller imports is re-exported from the module that holds it.
"""

